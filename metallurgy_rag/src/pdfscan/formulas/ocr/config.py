"""Настройки повторного распознавания формул."""

from dataclasses import dataclass

from pdfscan import paths

WORK_DIR = paths.DATA_DIR / 'formula_ocr'
CROPS_DIR = WORK_DIR / 'crops'
MANIFEST = WORK_DIR / 'manifest.jsonl'
RECOGNIZED = WORK_DIR / 'recognized.jsonl'
DECISIONS = WORK_DIR / 'decisions.jsonl'
REPORT = paths.REPORTS_DIR / 'formula_ocr.md'

# Сводка решений рядом с самим документом: правку видно там же, где данные.
SIDECAR_NAME = 'formula_ocr.jsonl'
# Резервная копия делается один раз, до первой правки файла.
BACKUP_SUFFIX = '.orig'


@dataclass
class FormulaOcrConfig:
    """Пороги и параметры прохода.

    Разрешение выше, чем при обычном рендере страниц: распознавание формул
    чувствительно к мелким деталям — индексы, штрихи, различие точки и запятой.
    Отступ вокруг рамки тоже больше, потому что разметка макета режет высокие
    дроби и корни по границе символов.
    """

    model_name: str = 'PP-FormulaNet_plus-L'
    batch_size: int = 1
    render_dpi: int = 300
    padding_pt: float = 6.0

    # Рамки бывают вырожденными: разметка иногда отдаёт полосу в один пиксель
    # или на всю страницу. Ни то, ни другое распознавать смысла нет.
    min_crop_px: int = 12
    max_crop_px: int = 2400

    # Кого пересматривать. Блок из текстового слоя по умолчанию не трогаем: там
    # индексы и греческие буквы лежат готовыми, и распознавание их только
    # испортит. Исключение — когда от формулы остался лишь её номер.
    include_ocr: bool = True
    include_cid: bool = True
    include_bare_numbers: bool = True

    # Мы распознаём картинку, а не текст, поэтому размер рамки — это прямая
    # оценка того, может ли внутри вообще оказаться формула. Ссылка «[1]»
    # занимает около сотни квадратных пунктов, маркер списка — вчетверо меньше,
    # тогда как даже узкая дробь в две строки даёт около пятисот. Порог ниже
    # отсекает первые и оставляет вторые; лишний прогон здесь не просто трата
    # времени, а риск получить уверенную выдумку на месте нормального знака.
    min_region_area_pt2: float = 350.0
    # Отдельный порог на сторону: вырожденную полосу площадь не поймает, если
    # она достаточно длинная.
    min_region_side_pt: float = 6.0

    # Тот же довод сверху, и здесь разделяет именно высота. Формула тянется в
    # ширину: даже система из четырёх реакций с длинными химическими членами
    # укладывается в сотню пунктов по вертикали, а девяносто пятая процентиль
    # по корпусу — шестьдесят семь. Всё, что выше ста шестидесяти, оказалось
    # таблицами и фазовыми диаграммами, на которых модель формул выдумывает
    # структуру от начала до конца. Площадь для этого не годится: широкая
    # многострочная реакция набирает её не хуже таблицы.
    max_region_height_pt: float = 160.0

    # Кандидат длиннее этого — почти всегда сорвавшееся распознавание, которое
    # ушло в повтор одного и того же куска.
    max_candidate_chars: int = 600

    # Спорные случаи по умолчанию не применяются: молча испортить формулу хуже,
    # чем оставить её плохой и заметной.
    accept_unsure: bool = False


DEFAULT = FormulaOcrConfig()
